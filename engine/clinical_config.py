"""
clinical_config.py — 临床规则的数值参数(第八棒)

所有数值都注明出处。分三类:
  【医生】访谈里医生/家长直接给的数 —— 不要凭直觉改,改了要在文档里说明
  【生理】公认生理常识(如血氧 <90% 为低氧)
  【工程】为实现规则而需要的参数(回看窗长、步进),可按数据集调

为什么单独一个文件:这些数会被反复质疑("30 哪来的?"),
把出处和数值放在一起,任何人一眼能查。
"""

from __future__ import annotations
from dataclasses import dataclass


@dataclass
class ClinicalConfig:
    # ---- R1 大发作主判据:心率升幅 + 持续时长 -------------------------
    # 【医生】"心率增高30至60次/分钟" → 取下界 30 作触发门限
    hr_rise_bpm: float = 30.0
    # 【医生】"持续时间超过45秒作为大发作的报警阈值"(医生明言是经验值,
    #         "后续可以随着穿戴数据积累的增多来调整优化")
    hr_sustain_s: float = 45.0
    # 【工程】回溯多久够用:45s 判据 + 余量
    hr_sustain_lookback_s: float = 120.0
    # 【工程】窗口步进,用于把"当前窗"折算进持续时长。
    #         SeizeIT2 用 2s,UCD 用 4s —— 跑别的数据集要改这个。
    window_hop_s: float = 2.0

    # ---- R2 心动过缓 / SUDEP 前兆 ------------------------------------
    # 【医生】"持续低于60次/分钟"
    brady_bpm: float = 60.0
    # 【医生】"建议设定5至10秒的异常时间作为报警触发条件"
    # 取**上界 10 秒**：实测 5 秒在 SeizeIT2 背景段本底 2.80/h（太吵），
    # 10 秒降到 0.80/h。见 validation/diag_brady.py。
    brady_sustain_s: float = 10.0
    # 【工程】相对基线的最小落差，与绝对门限**合取**：
    #         既要低于人群参考值 60，又要比自己平时低 15bpm 以上。
    # 实测定值（diag_brady3.py，背景 5 小时本底）：
    #         margin 0 → 0.80/h　5 → 0.60/h　10 → 0.40/h　**15 → 0**
    # 为什么必须合取：这批孩子里 sub-024/059/069/031 睡眠心率中位就在
    #         64-68bpm，深睡掉到 58 是正常生理；而 sub-046 基线 130bpm，
    #         掉到 60 已是 -70 的巨幅下降。单一门限两头都照顾不到。
    brady_margin_bpm: float = 15.0
    brady_lookback_s: float = 60.0

    # ---- R3 呼吸暂停 --------------------------------------------------
    # 【医生】"常因喉肌痉挛出现呼吸暂停,通常持续10至30秒" → 10 秒起报
    apnea_s: float = 10.0
    # 【医生】"常规发作憋气通常会在持续30秒到60秒" → 30 秒升级
    apnea_critical_s: float = 30.0
    # 【生理】呼吸率低于此值视为疑似暂停/严重抑制(次/分)
    apnea_rate: float = 6.0
    apnea_lookback_s: float = 120.0

    # ---- 连续性判定的采样缺口容忍（工程，但影响所有带时长的判据）------
    # 【工程】相邻样本间隔超过这个值就视为连续性断裂。
    # 实测必需（diag_brady2.py）：原实现只看非空样本，把 t=1210 与
    # t=62788 两个孤立低心率算成"连续 61578 秒心动过缓"。
    # 6 秒 ≈ 3 个 2 秒窗：容忍偶发丢点，不容忍整段缺值。
    # 发作期的肌电干扰恰好让 ECG 大量丢点，所以这条在最关键时刻最重要。
    max_gap_s: float = 6.0

    # ---- R4 血氧:延迟但高准确,用作升级确认 --------------------------
    # 【生理】相对个人基线下降 4 个点为有意义去饱和(临床常用 3-4%)
    desat_drop: float = 4.0
    # 【生理】孤立出现也不可忽视的降幅
    desat_drop_alone: float = 8.0
    # 【医生】"发作50秒-60秒,血氧才会出现变化" → 允许血氧滞后这么久,
    #         在此窗口内曾有风险抬头就算"与事件相关"
    desat_context_s: float = 90.0
    # 【工程】多高的既往风险算"此前已有异常"
    desat_context_risk: float = 0.35

    # ---- R5 癫痫持续状态:超过 2 分钟必报 ----------------------------
    # 【医生】"若患儿持续发作超过2分钟,设备必须提醒家长,以防致死性风险"
    prolonged_s: float = 120.0
    # 【工程】多高的风险算"仍在发作中"
    prolonged_risk: float = 0.40
    prolonged_lookback_s: float = 240.0

    # ---- R6 发作后高危期 ---------------------------------------------
    # 【医生】"仍需保持5至10分钟的高风险监测期" → 取上界 10 分钟更安全
    post_ictal_s: float = 600.0
    # 【工程】高危期内把两个门限各下调多少(绝对值)
    post_ictal_relief: float = 0.10

    @classmethod
    def for_hop(cls, hop_s: float) -> "ClinicalConfig":
        """按数据集的窗口步进生成配置。唯一需要随数据集变的就是这个。"""
        return cls(window_hop_s=float(hop_s))
